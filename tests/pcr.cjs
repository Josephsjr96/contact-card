const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'/home/joe/Work/vix/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const p=require('../samples/pcr/engine.js');
const base=(process.env.BASE_URL||'http://127.0.0.1:8088/').replace(/\/?$/,'/');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1160},reducedMotion:'reduce'});
  const page=await context.newPage(),errors=[],missing=[],external=[];
  const out=path.resolve(__dirname,'../qa');await fs.mkdir(out,{recursive:true});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.url().startsWith(base)&&r.status()>=400)missing.push([r.status(),r.url()]);});
  await page.goto(base+'#work');
  const card=page.locator('#proj-pcr');assert.ok(await card.isVisible());
  assert.ok(await card.evaluate(e=>e.classList.contains('project')));
  await page.screenshot({path:path.join(out,'pcr-work-card.png')});
  await page.getByRole('button',{name:'Ask Gaby',exact:true}).click();
  await page.locator('#gb-in').fill('What does VESPER PCR do?');await page.getByRole('button',{name:'Send',exact:true}).click();
  assert.match(await page.locator('.gb-body').innerText(),/single FASTA record/);
  await page.keyboard.press('Escape');
  await card.getByRole('link',{name:'Open live laboratory'}).click();
  await page.waitForSelector('.specimen');assert.equal(await page.locator('.specimen').count(),4);
  const onRequest=request=>{if(!request.url().startsWith(base)&&!request.url().startsWith('data:')&&!request.url().startsWith('blob:'))external.push(request.url());};
  page.on('request',onRequest);
  await page.locator('#importButton').click();
  const fixture=path.resolve(__dirname,'../samples/pcr/tests/fixtures/NC_001416.1-1-400.fasta');
  const fasta=await fs.readFile(fixture,'utf8'),seq=p.parseFasta(fasta).seq;
  await page.locator('#fastaFile').setInputFiles(fixture);
  await page.waitForFunction(()=>document.querySelector('#customFasta').value.startsWith('>NC_001416.1:1-400'));
  await page.fill('#customName','Lambda reference fragment');
  await page.fill('#customFwd',seq.slice(0,20));await page.fill('#customRev',p.rc(seq.slice(-20)));
  await page.locator('#importForm [type=submit]').click();
  await page.locator('#importDialog').waitFor({state:'hidden'});
  assert.equal(await page.locator('.specimen').count(),5);
  assert.match(await page.locator('#inspector').innerText(),/400 bp/);
  await page.locator('[data-slot="0"]').click();await page.click('[data-load-id="CUSTOM-1"]');await page.selectOption('#speed','16');await page.click('#startButton');
  await page.waitForFunction(()=>document.querySelector('#phaseLabel').textContent==='PROTOCOL COMPLETE',null,{timeout:30000});
  assert.match(await page.locator('#results').innerText(),/CONTROLS VALID/);
  const done=page.waitForEvent('download');await page.click('#exportButton');
  const downloaded=await done,exportPath=path.join(out,'pcr-real-sequence-run.json');await downloaded.saveAs(exportPath);
  const run=JSON.parse(await fs.readFile(exportPath,'utf8'));
  assert.equal(run.datasets[0].seq,seq);assert.equal(run.samples[0].product.length,400);
  assert.equal(run.samples[0].call,'POSITIVE');assert.equal(run.wells.length,9);assert.equal(run.runQC.invalid,false);
  assert.equal(run.advisory.requested,false);assert.equal(run.advisory.status,'not_requested');
  await page.waitForTimeout(3700);await page.locator('.telemetry').screenshot({path:path.join(out,'pcr-real-sequence-results.png')});
  await page.locator('.fault-controls summary').click();await page.check('#contamination');assert.equal(await page.locator('#exportButton').isDisabled(),true);
  await page.click('#startButton');await page.waitForFunction(()=>document.querySelector('#phaseLabel').textContent==='PROTOCOL COMPLETE',null,{timeout:30000});
  assert.equal(await page.locator('.call.invalid').count(),3);
  await page.waitForTimeout(3700);await page.locator('.telemetry').screenshot({path:path.join(out,'pcr-contaminated-results.png')});
  for(const width of [390,768,1440]){await page.setViewportSize({width,height:900});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Laboratory overflow at '+width);}
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(out,'pcr-mobile.png'),fullPage:true});
  await page.getByRole('link',{name:'DNA import guide'}).click();assert.match(await page.locator('h1').innerText(),/Real sequence input/);
  const reference=await context.request.get(base+'samples/pcr/tests/fixtures/NC_001416.1-1-400.fasta');assert.equal(reference.status(),200);assert.equal(await reference.text(),fasta);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Guide overflow');
  await page.getByRole('link',{name:'Back to projects'}).click();await page.waitForURL('**/#work');
  assert.deepEqual(external,[],'DNA workflow made external requests');assert.deepEqual(errors,[]);assert.deepEqual(missing,[]);
  const report={base,passed:true,checkedAt:new Date().toISOString(),reference:'NC_001416.1:1-400',length:seq.length,productLength:400,wellCount:run.wells.length,call:run.samples[0].call,controlValid:!run.runQC.invalid,checks:['Existing Work-card style and live link','PCR assistant reply','Real NCBI FASTA file upload','Correct sequence and 400-bp product retained in JSON','Control-valid completion','Contamination invalidates imported assay','Stale-export blocking','390/768/1440px layout','Guide and fixture download','Return to Work','No DNA uploads/external requests','No page errors or missing assets']};
  await fs.writeFile(path.join(out,'pcr-report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
